export function translate(language: Language, key: StringKey, vars?: Record<string, string | number>): string {
  const template = (language === 'en' ? en[key] : undefined) ?? id[key];
  return vars ? template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : template;
}

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;
export const translator = (language: Language): Translate => (key, vars) => translate(language, key, vars);

