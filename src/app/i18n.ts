/**
 * The two-letter region the catalog is asked for (YouTube Music ranks and filters results by it, so the phone in
 * Indonesia and a TV left on the default US region do not see the same list). The TV's own country first, then the
 * region of its locale ("id-ID"), then the browser's; `undefined` when none says (the service then uses US).
 */
export function detectRegion(source: { webOSCountry?: string; webOSLocale?: string; navigatorLanguage?: string } = {}): string | undefined {
  const w = typeof window === 'undefined' ? undefined : (window as unknown as { webOSSystem?: { country?: string; locale?: string } });
  const fromLocale = (value?: string) => /[-_]([A-Za-z]{2})$/.exec(value ?? '')?.[1];
  const found = [source.webOSCountry ?? w?.webOSSystem?.country, fromLocale(source.webOSLocale ?? w?.webOSSystem?.locale), fromLocale(source.navigatorLanguage ?? (typeof navigator === 'undefined' ? '' : navigator.language))]
    .map((value) => value?.toUpperCase())
    .find((value): value is string => !!value && /^[A-Z]{2}$/.test(value));
  return found;
}

export function detectLanguage(source: { webOSLocale?: string; navigatorLanguage?: string } = {}): Language {
  const w = typeof window === 'undefined' ? undefined : (window as unknown as { webOSSystem?: { locale?: string } });
  const locale = source.webOSLocale ?? w?.webOSSystem?.locale ?? source.navigatorLanguage ?? (typeof navigator === 'undefined' ? '' : navigator.language) ?? '';
  return /^(id|in)\b/i.test(locale) ? 'id' : 'en';
}
